local M = {}
function M.language()
    local lang = G_reader_settings:readSetting("language") or "en"
    return (lang == "ru" or lang:match("^ru[_%-]")) and "ru" or "en"
end
function M.tr(text)
    return M.language() == "ru" and ru[text] or text
end
return M
